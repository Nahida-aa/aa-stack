//! 从 `assets/icons/*.svg` 的文件名生成 `IconName` 枚举（gpui-kit 同款做法）。
//!
//! SVG 文件名是唯一事实源：加图标 = 放一个文件再重编译，删图标 = 移走文件。
//! 生成内容只有两样 —— 变体清单与 `path()` 的 match 表；strum/serde 的 derive
//! 原样保留（`IntoEnumIterator`、`EnumString`、`IntoStaticStr` 都有消费者）。
//!
//! 改名规则照 gpui-kit 的 `crates/assets/build.rs`：`snake_case` 文件名逐段
//! 首字母大写拼成 PascalCase 变体（`generic_close` → `GenericClose`），非法
//! 名字（非字母开头、含非字母数字、重名）直接 panic 挡在编译期。

#![allow(clippy::disallowed_methods, reason = "build scripts are exempt")]

use std::{collections::BTreeMap, env, fmt::Write as _, fs, path::PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // 资产根在仓库根（与 aa_assets_core 的 RustEmbed 同一份目录）。
    let icons_dir = manifest_dir.join("../../../assets/icons");
    println!("cargo:rerun-if-changed={}", icons_dir.display());

    // BTreeMap 让变体按名字序输出 —— 文件增删不会打乱其余变体的顺序。
    let mut icons = BTreeMap::new();
    for entry in fs::read_dir(&icons_dir).expect("bundled icons directory") {
        let path = entry.expect("read icon directory entry").path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("svg") {
            continue;
        }
        let stem = path.file_stem().unwrap().to_str().expect("UTF-8 icon name");
        let variant: String = stem
            .split(['-', '_', '.'])
            .filter(|part| !part.is_empty())
            .map(|part| {
                let mut chars = part.chars();
                let first = chars.next().unwrap();
                format!(
                    "{}{}",
                    first.to_ascii_uppercase(),
                    chars.as_str().to_ascii_lowercase()
                )
            })
            .collect();
        assert!(
            variant.starts_with(|c: char| c.is_ascii_alphabetic())
                && variant.chars().all(|c: char| c.is_ascii_alphanumeric()),
            "invalid icon name: {stem}"
        );
        assert!(
            icons.insert(variant, stem.to_owned()).is_none(),
            "duplicate icon variant: {stem}"
        );
    }
    assert!(!icons.is_empty(), "bundled icons must not be empty");

    let mut code = String::new();
    writeln!(
        code,
        "// @generated by aa_icons 的 build.rs —— 别手改；加/删图标 = 改 assets/icons/ 下的 SVG 文件。"
    )
    .unwrap();
    // derive 与手维护时代完全一致（外加 Hash）：消费方依赖 strum 的
    // `IntoEnumIterator`（图标全集展示页）与 `EnumString`（资产目录反解析），
    // serde 保留是维持序列化行为不变（默认按变体名 PascalCase 输出）。
    writeln!(
        code,
        "#[derive(\n    Debug, PartialEq, Eq, Copy, Clone, Hash,\n    strum::EnumIter, strum::EnumString, strum::IntoStaticStr,\n    serde::Serialize, serde::Deserialize,\n)]"
    )
    .unwrap();
    writeln!(code, "#[strum(serialize_all = \"snake_case\")]").unwrap();
    writeln!(code, "pub enum IconName {{").unwrap();
    for variant in icons.keys() {
        writeln!(code, "    {variant},").unwrap();
    }
    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();
    writeln!(code, "impl IconName {{").unwrap();
    writeln!(code, "    /// Returns the path to this icon.").unwrap();
    writeln!(code, "    pub fn path(&self) -> std::sync::Arc<str> {{").unwrap();
    writeln!(code, "        match self {{").unwrap();
    for (variant, stem) in &icons {
        writeln!(
            code,
            "            IconName::{variant} => std::sync::Arc::from(\"icons/{stem}.svg\"),"
        )
        .unwrap();
    }
    writeln!(code, "        }}").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("icon_name.rs"), code).unwrap();
}
